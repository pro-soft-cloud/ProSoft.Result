using System.Diagnostics.CodeAnalysis;

namespace ProSoft.Result;

/// <summary>
/// Class PagedResult. This class cannot be inherited.
/// Implements the <see cref="System.IDisposable" />
/// Implements the <see cref="System.IAsyncDisposable" />
/// </summary>
/// <typeparam name="TData">The type of the t data.</typeparam>
/// <seealso cref="System.IDisposable" />
/// <seealso cref="System.IAsyncDisposable" />
public sealed class PagedResult<TData> : IDisposable, IAsyncDisposable where TData : class
{
	/// <summary>
	/// Gets or sets the list items.
	/// </summary>
	/// <value>The list items.</value>
	public List<TData> ListItems { get; set; } = [];

	/// <summary>
	/// Gets or sets the status.
	/// </summary>
	/// <value>The status.</value>
	public ResultStatus Status { get; set; }

	/// <summary>
	/// Gets or sets the total count.
	/// </summary>
	/// <value>The total count.</value>
	public long TotalCount { get; set; } = 0;

	/// <summary>
	/// Gets or sets the size of the page.
	/// </summary>
	/// <value>The size of the page.</value>
	public long PageSize { get; set; } = 10;

	/// <summary>
	/// Gets or sets the current page.
	/// </summary>
	/// <value>The current page.</value>
	public long CurrentPage { get; set; } = 1;

	/// <summary>
	/// Gets or sets the total pages.
	/// </summary>
	/// <value>The total pages.</value>
	public long TotalPages { get; set; } = 1;

	#region IDisposable implementation

	/// <summary>
	/// Releases the unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseUnmanagedResources()
	{
		// TODO release unmanaged resources here
	}

	/// <summary>
	/// Releases the managed resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseManagedResources()
	{
		// TODO release managed resources here
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or resetting unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public void Dispose()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or
	/// resetting unmanaged resources asynchronously.
	/// </summary>
	/// <returns>A Task&lt;ValueTask&gt; representing the asynchronous operation.</returns>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public async ValueTask DisposeAsync()
	{
		await Task.CompletedTask;
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Finalizes an instance of the <see cref="PagedResult"/> class.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	~PagedResult()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
	}

	#endregion
}
