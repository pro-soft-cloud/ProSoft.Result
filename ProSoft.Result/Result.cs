using System.Diagnostics.CodeAnalysis;

namespace ProSoft.Result;

/// <summary>
/// Class Result. This class cannot be inherited.
/// Implements the <see cref="System.IDisposable" />
/// Implements the <see cref="System.IAsyncDisposable" />
/// </summary>
/// <typeparam name="TData">The type of the t data.</typeparam>
/// <seealso cref="System.IDisposable" />
/// <seealso cref="System.IAsyncDisposable" />
public sealed class Result<TData> : IDisposable, IAsyncDisposable where TData : class
{
	/// <summary>
	/// Gets or sets the item.
	/// </summary>
	/// <value>The item.</value>
	public TData? Item { get; set; }

	/// <summary>
	/// Gets or sets the status.
	/// </summary>
	/// <value>The status.</value>
	public ResultStatus Status { get; set; }

	/// <summary>
	/// Gets a value indicating whether this instance has messages.
	/// </summary>
	/// <value><c>true</c> if this instance has messages; otherwise, <c>false</c>.</value>
	public bool HasMessages => Messages.Count > 0;

	/// <summary>
	/// Gets a value indicating whether this instance has infos.
	/// </summary>
	/// <value><c>true</c> if this instance has infos; otherwise, <c>false</c>.</value>
	public bool HasInfos => Messages.Count(x => x.Type == MessageType.Info) > 0;

	/// <summary>
	/// Gets a value indicating whether this instance has hints.
	/// </summary>
	/// <value><c>true</c> if this instance has hints; otherwise, <c>false</c>.</value>
	public bool HasHints => Messages.Count(x => x.Type == MessageType.Hint) > 0;

	/// <summary>
	/// Gets a value indicating whether this instance has warnings.
	/// </summary>
	/// <value><c>true</c> if this instance has warnings; otherwise, <c>false</c>.</value>
	public bool HasWarnings => Messages.Count(x => x.Type == MessageType.Warning) > 0;

	/// <summary>
	/// Gets a value indicating whether this instance has errors.
	/// </summary>
	/// <value><c>true</c> if this instance has errors; otherwise, <c>false</c>.</value>
	public bool HasErrors => Messages.Count(x => x.Type == MessageType.Error) > 0;

	/// <summary>
	/// Gets or sets the messages.
	/// </summary>
	/// <value>The messages.</value>
	public List<Message> Messages { get; set; } = [];

	/// <summary>
	/// Initializes a new instance of the <see cref="Result{TData}"/> class.
	/// </summary>
	public Result() { }

	/// <summary>
	/// Initializes a new instance of the <see cref="Result{TData}"/> class.
	/// </summary>
	/// <param name="data">The data.</param>
	public Result(TData data)
	{
		Item = data;
	}

	/// <summary>
	/// Initializes a new instance of the <see cref="Result{TData}"/> class.
	/// </summary>
	/// <param name="data">The data.</param>
	/// <param name="status">The status.</param>
	public Result(TData data, ResultStatus status)
	{
		Item = data;
		Status = status;
	}

	#region IDisposable implementation

	/// <summary>
	/// Releases the unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseUnmanagedResources()
	{
		// Release unmanaged resources here
	}

	/// <summary>
	/// Releases the managed resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseManagedResources()
	{
		// Release managed resources here
		Item = null;
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or resetting unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public void Dispose()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or
	/// resetting unmanaged resources asynchronously.
	/// </summary>
	/// <returns>A Task&lt;ValueTask&gt; representing the asynchronous operation.</returns>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public async ValueTask DisposeAsync()
	{
		await Task.CompletedTask;
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Finalizes an instance of the <see cref="Result"/> class.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	~Result()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
	}

	#endregion
}
