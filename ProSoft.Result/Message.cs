using System.Diagnostics.CodeAnalysis;

namespace ProSoft.Result;

/// <summary>
/// Class Message. This class cannot be inherited.
/// Implements the <see cref="System.IDisposable" />
/// Implements the <see cref="System.IAsyncDisposable" />
/// </summary>
/// <seealso cref="System.IDisposable" />
/// <seealso cref="System.IAsyncDisposable" />
public sealed class Message : IDisposable, IAsyncDisposable
{
	/// <summary>
	/// Gets or sets the type.
	/// </summary>
	/// <value>The type.</value>
	public MessageType Type { get; set; }

	/// <summary>
	/// Gets or sets the text.
	/// </summary>
	/// <value>The text.</value>
	public string Text { get; set; }

	/// <summary>
	/// Gets or sets the reference identifier.
	/// </summary>
	/// <value>The reference identifier.</value>
	public string ReferenceId { get; set; } = string.Empty;

	/// <summary>
	/// Gets or sets the name of the reference property.
	/// </summary>
	/// <value>The name of the reference property.</value>
	public string ReferencePropertyName { get; set; } = string.Empty;

	/// <summary>
	/// Initializes a new instance of the <see cref="Message"/> class.
	/// </summary>
	/// <param name="type">The type.</param>
	/// <param name="text">The text.</param>
	public Message(MessageType type, string text)
	{
		Type = type;
		Text = text;
	}

	/// <summary>
	/// Initializes a new instance of the <see cref="Message"/> class.
	/// </summary>
	/// <param name="type">The type.</param>
	/// <param name="text">The text.</param>
	/// <param name="referenceId">The reference identifier.</param>
	public Message(MessageType type, string text, string referenceId)
	{
		Type = type;
		Text = text;
		ReferenceId = referenceId;
	}

	/// <summary>
	/// Initializes a new instance of the <see cref="Message"/> class.
	/// </summary>
	/// <param name="type">The type.</param>
	/// <param name="text">The text.</param>
	/// <param name="referenceId">The reference identifier.</param>
	/// <param name="referencePropertyName">Name of the reference property.</param>
	public Message(MessageType type, string text, string referenceId, string referencePropertyName)
	{
		Type = type;
		Text = text;
		ReferenceId = referenceId;
		ReferencePropertyName = referencePropertyName;
	}

	#region IDisposable implementation

	/// <summary>
	/// Releases the unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseUnmanagedResources()
	{
		// TODO release unmanaged resources here
	}

	/// <summary>
	/// Releases the managed resources.
	/// </summary>
	/// <autogeneratedoc />
	private void ReleaseManagedResources()
	{
		// TODO release managed resources here
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or resetting unmanaged resources.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public void Dispose()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Performs application-defined tasks associated with freeing, releasing, or
	/// resetting unmanaged resources asynchronously.
	/// </summary>
	/// <returns>A Task&lt;ValueTask&gt; representing the asynchronous operation.</returns>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	public async ValueTask DisposeAsync()
	{
		await Task.CompletedTask;
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
		GC.SuppressFinalize(this);
	}

	/// <summary>
	/// Finalizes an instance of the <see cref="Message"/> class.
	/// </summary>
	/// <autogeneratedoc />
	[ExcludeFromCodeCoverage]
	~Message()
	{
		ReleaseUnmanagedResources();
		ReleaseManagedResources();
	}

	#endregion
}
